import asyncHandler from 'express-async-handler';
import User from '../models/User.js';
import { success, error } from '../utils/sendResponse.js';

const TEAM_ROLES = ['dispatcher', 'sales_agent', 'carrier', 'admin'];

/**
 * @route   GET /api/users
 * @desc    List users, filterable by ?role and ?isActive. Admin-created team
 *          members management. Never returns password hashes.
 * @access  Private/Admin
 */
export const getUsers = asyncHandler(async (req, res) => {
  const { role, isActive } = req.query;
  const query = {};
  if (role) query.role = role;
  if (isActive === 'true') query.isActive = true;
  if (isActive === 'false') query.isActive = false;

  const users = await User.find(query).select('-password').sort('name');
  return success(res, 200, users, 'Users retrieved');
});

/**
 * @route   GET /api/users/:id
 * @desc    Get a single user
 * @access  Private/Admin
 */
export const getUser = asyncHandler(async (req, res) => {
  const user = await User.findById(req.params.id).select('-password');
  if (!user) return error(res, 404, 'User not found');
  return success(res, 200, user, 'User retrieved');
});

/**
 * @route   POST /api/users
 * @desc    Admin creates a team member. Password is set/generated by the admin
 *          on-screen — there is no email invite or verification anywhere.
 * @access  Private/Admin
 */
export const createUser = asyncHandler(async (req, res) => {
  const { name, email, password, role, workLocation } = req.body;

  if (!name || !email || !password) {
    return error(res, 400, 'Name, email, and password are required');
  }
  if (!TEAM_ROLES.includes(role)) {
    return error(res, 400, 'Invalid role');
  }

  const existing = await User.findOne({ email: email.toLowerCase() });
  if (existing) return error(res, 409, 'A user with this email already exists');

  const user = await User.create({
    name,
    email,
    password,
    role,
    workLocation: ['remote', 'onsite'].includes(workLocation) ? workLocation : undefined,
    isFirstLogin: true,
  });

  const safe = user.toObject();
  delete safe.password;
  return success(res, 201, safe, 'User created');
});

/**
 * @route   PATCH /api/users/:id
 * @desc    Update a team member (name, role, workLocation, isActive) and,
 *          optionally, reset their password.
 * @access  Private/Admin
 */
export const updateUser = asyncHandler(async (req, res) => {
  const user = await User.findById(req.params.id);
  if (!user) return error(res, 404, 'User not found');

  const { name, role, workLocation, isActive, password } = req.body;

  if (name !== undefined) user.name = name;
  if (role !== undefined) {
    if (!TEAM_ROLES.includes(role)) return error(res, 400, 'Invalid role');
    user.role = role;
  }
  if (workLocation !== undefined) {
    user.workLocation = ['remote', 'onsite'].includes(workLocation) ? workLocation : undefined;
  }
  if (isActive !== undefined) user.isActive = !!isActive;
  if (password) {
    user.password = password; // re-hashed by the pre-save hook
    user.isFirstLogin = true;
  }

  await user.save();

  const safe = user.toObject();
  delete safe.password;
  return success(res, 200, safe, 'User updated');
});

/**
 * @route   DELETE /api/users/:id
 * @desc    Permanently delete a team member from the database
 * @access  Private/Admin
 */
export const deleteUser = asyncHandler(async (req, res) => {
  const user = await User.findById(req.params.id);
  if (!user) return error(res, 404, 'User not found');

  if (user.role === 'admin') {
    return error(res, 400, 'Admin accounts cannot be removed here');
  }

  await User.findByIdAndDelete(req.params.id);

  return success(res, 200, null, 'User deleted');
});

export default { getUsers, getUser, createUser, updateUser, deleteUser };
